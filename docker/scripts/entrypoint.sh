    # Deprecated: Claude Auth is now handled via direct API in the backend
    echo "🔒 Claude Auth (Deprecated)"
}

setup_claude_wrapper() {
    # Deprecated: Claude Code wrapper is no longer used
    echo "🛡️  Claude Wrapper (Deprecated)"
}

setup_bash_config() {
    # 3. Bash aliases and Welcome Message
    cat >> /home/coder/.bashrc << 'BASHRC'
export PATH="$HOME/.local/bin:$PATH"
alias claude='claude-code'
alias ask='claude-code'


BASHRC

    # 4. Interactive Mode logging hooks
    mkdir -p /home/coder/.claude/hooks
    if [ -f "/usr/local/bin/log-prompt.sh" ]; then
        cp /usr/local/bin/log-prompt.sh /home/coder/.claude/hooks/log-prompt.sh
        chmod +x /home/coder/.claude/hooks/log-prompt.sh
    fi
}

setup_git() {
    # 5. Git & Workspace Initialization
    echo "📝 Configuring Git..."
    git config --global user.name "${GIT_USER_NAME:-Candidate}"
    git config --global user.email "${GIT_USER_EMAIL:-candidate@assessment.local}"
    git config --global init.defaultBranch main

    if [ ! -d "/workspace/.git" ]; then
        echo "📁 Initializing workspace..."
        cd /workspace
        git init
        git config user.email "${GIT_USER_EMAIL:-candidate@hermes.com}"
        git config user.name "${GIT_USER_NAME:-Candidate}"
        git add -A 2>/dev/null || true
        git commit -m "Initial workspace setup" 2>/dev/null || true
    fi
}

setup_env_local() {
    # 6. Generate .env.local
    echo "🔑 Provisioning credentials to .env.local..."
    ENV_FILE="/workspace/.env.local"
    echo "# Auto-generated by Hermes Assessment Environment" > "$ENV_FILE"
    KEYS=("CANDIDATE_ID" "SESSION_ID" "NEXT_PUBLIC_SUPABASE_URL" "NEXT_PUBLIC_SUPABASE_ANON_KEY" "GEMINI_BASE_URL" "GOOGLE_BASE_URL" "GOOGLE_API_KEY" "QUARTERMASTER_API_URL")

    for KEY in "${KEYS[@]}"; do
        if [ -n "${!KEY}" ]; then
            echo "$KEY=${!KEY}" >> "$ENV_FILE"
        fi
    done

    # Force development servers to bind to all interfaces for external access
    echo "HOST=0.0.0.0" >> "$ENV_FILE"
    echo "PORT=3000" >> "$ENV_FILE"
}

# setup_test_deps removed - now runs at build time in Dockerfile (Layer 6)
# This saves ~1-2s on every container startup

start_dev_server() {
    # 8. Auto-start the development server
    echo "🚀 Starting development server via 'npm run dev'..."
    cd /workspace
    # Start npm run dev in the background, redirect output to a log file
    # We use npm run dev to pick up polling settings from package.json
    nohup npm run dev > /workspace/.dev-server.log 2>&1 &
    
    # Warm up server in background to trigger initial compilation
    (
        echo "🔥 Waiting for Next.js to be ready..."
        # Wait for port 3000 to be open and responding (max 60s)
        for i in {1..60}; do
            # Check if port is open AND if curl can get a response
            # We use localhost:3000 but Next.js will see it as a request to the root
            if curl -s -f http://localhost:3000/ > /dev/null 2>&1; then
                echo "✅ Next.js is ready! Compilation triggered."
                # One more request just to be sure
                curl -s http://localhost:3000/ > /dev/null
                break
            fi
            [ $((i % 5)) -eq 0 ] && echo "⏳ Waiting for server to respond on port 3000... ($i/60)"
            sleep 1
        done
    ) &

    echo "✅ Development server background process started"
    echo "   Logs: tail -f /workspace/.dev-server.log"
}

# ============================================
# BACKGROUND SETUP FUNCTION
# Runs AFTER code-server starts
# ============================================
run_background_setup() {
    echo "⏳ Running background setup..."

    # Fix workspace permissions - simplified
    echo "🔧 Fixing workspace permissions..."
    sudo chown -R coder:coder /workspace/.next /workspace/.env* 2>/dev/null || true &
    
    measure_step "setup_claude_auth" setup_claude_auth
    measure_step "setup_claude_wrapper" setup_claude_wrapper
    measure_step "setup_bash_config" setup_bash_config
    measure_step "setup_git" setup_git
    measure_step "setup_env_local" setup_env_local
    # setup_test_deps removed - now in Dockerfile
    measure_step "start_dev_server" start_dev_server


    # Final ownership check
    chown -R coder:coder /home/coder/.claude 2>/dev/null || true

    echo "✅ Background setup complete!"
}

# ============================================
# MAIN: Start code-server
# ============================================

# CRITICAL: Ensure settings are valid and owned by coder BEFORE starting
# This prevents code-server from loading default settings (ignoring our config)
check_settings() {
    SETTINGS_PATH="/home/coder/.local/share/code-server/User/settings.json"
    BACKUP_PATH="/home/coder/.local/share/code-server/User/settings.json.bak"
    
    echo "⚙️  Enforcing default settings..."
    # Always overwrite with enforced settings to prevent persistence of theme changes etc.
    if [ -f "$BACKUP_PATH" ]; then
         cp "$BACKUP_PATH" "$SETTINGS_PATH"
         sudo chown coder:coder "$SETTINGS_PATH"
         echo "✅ Settings enforced from backup"
    else
         echo "⚠️  Backup settings missing, skipping enforcement"
    fi

    # Force remove ALL extensions directly in the entrypoint
    # This runs synchronously BEFORE code-server starts to prevent them from loading
    echo "🚫 Removing ALL extensions..."
    
    # Remove ALL extensions from all possible locations
    rm -rf /home/coder/.local/share/code-server/extensions/* 2>/dev/null || true
    rm -rf /home/coder/.vscode-server/extensions/* 2>/dev/null || true
    
    # Remove extension state and cache
    rm -rf /home/coder/.local/share/code-server/CachedExtensions* 2>/dev/null || true
    rm -rf /home/coder/.local/share/code-server/CachedExtensionVSIXs* 2>/dev/null || true
    
    # Remove any extension-related state
    rm -rf /home/coder/.local/share/code-server/User/workspaceStorage/* 2>/dev/null || true
    rm -rf /home/coder/.local/share/code-server/User/globalStorage/* 2>/dev/null || true
    
    # Disable all views in the UI state
    find /home/coder/.local/share/code-server -name "state.vscdb*" -exec rm -f {} \; 2>/dev/null || true
    
    echo "   ✓ All extensions removed"
}

echo "🛠️  Verifying configuration..."
check_settings

# Fix workspace permissions synchronously for the root folder
# This ensures code-server can actually read the workspace directory on launch
echo "🔧 Fixing workspace permissions..."
sudo chown coder:coder /workspace

# Robust CSS injection: Inject custom CSS directly into the workbench HTML
# This ensures UI elements are hidden even if extensions are disabled
echo "🎨 Injecting custom CSS into workbench..."
WORKBENCH_HTML=$(find /usr/lib/code-server -name "workbench.html" 2>/dev/null | head -n 1)
CUSTOM_CSS="/home/coder/.local/share/code-server/custom.css"

if [ -f "$WORKBENCH_HTML" ] && [ -f "$CUSTOM_CSS" ]; then
    CSS_CONTENT=$(cat "$CUSTOM_CSS" | tr -d '\n' | sed 's/"/\\"/g')
    sed -i "s|<\/head>|<style>$CSS_CONTENT</style><\/head>|" "$WORKBENCH_HTML"
    echo "   ✓ CSS injected into $WORKBENCH_HTML"
else
    echo "   ⚠️  Could not find workbench.html or custom.css for injection"
fi

# SIMPLE SOLUTION: Hide chat view by modifying UI state
echo "🎯 Hiding chat view in UI state..."
UI_STATE_DB="/home/coder/.local/share/code-server/User/globalStorage/state.vscdb"
WORKSPACE_STATE="/home/coder/.local/share/code-server/User/workspaceStorage"

# Create a script to hide the chat panel view
cat > /tmp/hide-chat.js << 'EOF'
// This will be injected into VS Code's settings to hide the chat panel
const fs = require('fs');
const path = require('path');

const settingsPath = '/home/coder/.local/share/code-server/User/settings.json';

try {
    let settings = {};
    if (fs.existsSync(settingsPath)) {
        settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8'));
    }
    
    // Hide the chat panel in the activity bar
    settings['workbench.panel.defaultLocation'] = 'bottom';
    settings['workbench.activityBar.iconClickBehavior'] = 'toggle';
    
    // Write back
    fs.writeFileSync(settingsPath, JSON.stringify(settings, null, 4));
    console.log('✓ Chat view hidden in settings');
} catch (err) {
    console.error('Failed to modify settings:', err);
}
EOF

# Also directly modify the UI state to close the chat panel
mkdir -p /home/coder/.local/share/code-server/User/globalStorage
cat > /home/coder/.local/share/code-server/User/globalStorage/state.json << 'EOF'
{
    "panel.hidden": "[\"workbench.panel.chat\"]",
    "sideBar.hidden": "[\"workbench.view.extension.github-copilot-chat\"]",
    "workbench.activity.pinnedViewlets2": "[]",
    "workbench.panel.chat.hidden": true,
    "workbench.view.extension.github-copilot-chat.hidden": true
}
EOF

echo "   ✓ Chat view hidden in UI state"

# FINAL SOLUTION: Inject JavaScript to hide Copilot panel after page loads
echo "🎯 Adding Copilot panel hider script..."
cat > /home/coder/.local/share/code-server/hide-copilot.js << 'EOF'
(function() {
    console.log('[Hermes] Copilot panel hider loaded');
    
    function hideCopilotPanel() {
        let style = document.getElementById('hermes-hide-copilot');
        if (!style) {
            style = document.createElement('style');
            style.id = 'hermes-hide-copilot';
            style.textContent = `
                .part.sidebar.right,
                .sidebar.right,
                [id*="workbench.view.extension.github-copilot"],
                [id*="workbench.panel.chat"],
                [id*="workbench.view.chat"],
                .activitybar .codicon-comment-discussion,
                .activitybar [aria-label*="Chat"],
                .activitybar [aria-label*="Copilot"],
                .composite-bar [aria-label*="Chat"],
                .composite-bar [aria-label*="Copilot"] {
                    display: none !important;
                    visibility: hidden !important;
                    width: 0 !important;
                    height: 0 !important;
                }
            `;
            document.head.appendChild(style);
            console.log('[Hermes] CSS injected');
        }
        
        const selectors = [
            '.part.sidebar.right',
            '[id*="workbench.view.extension.github-copilot"]',
            '[id*="workbench.panel.chat"]',
            '.activitybar .codicon-comment-discussion',
            '.activitybar [aria-label*="Chat"]',
            '.activitybar [aria-label*="Copilot"]'
        ];
        
        selectors.forEach(selector => {
            document.querySelectorAll(selector).forEach(el => {
                el.style.display = 'none';
                el.style.visibility = 'hidden';
            });
        });
    }
    
    hideCopilotPanel();
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', hideCopilotPanel);
    }
    setInterval(hideCopilotPanel, 1000);
    const observer = new MutationObserver(hideCopilotPanel);
    observer.observe(document.documentElement, { childList: true, subtree: true });
    console.log('[Hermes] Copilot panel hider active');
})();
EOF

# Inject script tag into workbench HTML
WORKBENCH_HTML=$(find /usr/lib/code-server -name "workbench.html" 2>/dev/null | head -n 1)
if [ -f "$WORKBENCH_HTML" ]; then
    grep -q "hide-copilot.js" "$WORKBENCH_HTML" || \
    sed -i 's|</body>|<script src="/hide-copilot.js"></script></body>|' "$WORKBENCH_HTML"
    echo "   ✓ Copilot hider script linked"
fi

# Test dependencies are now linked at build time in Dockerfile (Layer 6)
# No need to run setup_test_deps here - saves ~1-2s on startup

echo "🖥️  Starting code-server on 0.0.0.0:8080..."
START_TIME=$(date +%s%3N)

# Run remaining heavy setup tasks in background
run_background_setup &

# Start code-server (this blocks and keeps container running)
# Open the workspace folder
# Disable extensions completely by pointing to a non-existent directory
# Log startup performance metric
END_TIME=$(date +%s%3N)
STARTUP_DURATION=$((END_TIME - START_TIME))
log_metric "code_server_startup" "$STARTUP_DURATION"

exec code-server \
  --bind-addr 0.0.0.0:8080 \
  --auth none \
  --disable-workspace-trust \
  --disable-getting-started-override \
  --extensions-dir /tmp/no-extensions \
  --user-data-dir /home/coder/.local/share/code-server \
  /workspace

