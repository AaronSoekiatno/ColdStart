}

setup_git() {
    # 5. Git & Workspace Initialization
    echo "📝 Configuring Git..."
    git config --global user.name "${GIT_USER_NAME:-Candidate}"
    git config --global user.email "${GIT_USER_EMAIL:-candidate@assessment.local}"
    git config --global init.defaultBranch main

    if [ ! -d "/workspace/.git" ]; then
        echo "📁 Initializing workspace..."
        cd /workspace
        git init
        git config user.email "${GIT_USER_EMAIL:-candidate@hermes.com}"
        git config user.name "${GIT_USER_NAME:-Candidate}"
        git add -A 2>/dev/null || true
        git commit -m "Initial workspace setup" 2>/dev/null || true
    fi
}

setup_env_local() {
    # 6. Generate .env.local
    echo "🔑 Provisioning credentials to .env.local..."
    ENV_FILE="/workspace/.env.local"
    echo "# Auto-generated by Hermes Assessment Environment" > "$ENV_FILE"
    KEYS=("CANDIDATE_ID" "SESSION_ID" "NEXT_PUBLIC_SUPABASE_URL" "NEXT_PUBLIC_SUPABASE_ANON_KEY" "GEMINI_BASE_URL" "GOOGLE_BASE_URL" "GOOGLE_API_KEY" "QUARTERMASTER_API_URL")

    for KEY in "${KEYS[@]}"; do
        if [ -n "${!KEY}" ]; then
            echo "$KEY=${!KEY}" >> "$ENV_FILE"
        fi
    done

    # Force development servers to bind to all interfaces for external access
    echo "HOST=0.0.0.0" >> "$ENV_FILE"
    echo "PORT=3000" >> "$ENV_FILE"
}

setup_test_deps() {
    # 7. Link test dependencies into workspace node_modules
    echo "🧪 Setting up test dependencies..."

    # Ensure workspace node_modules exists
    mkdir -p /workspace/node_modules

    # List of test packages to symlink from assessment node_modules
    TEST_PACKAGES=(
        "vitest"
        "@vitejs/plugin-react-swc"
        "@testing-library/react"
        "@testing-library/jest-dom"
        "happy-dom"
        "@typescript-eslint/parser"
        "@typescript-eslint/typescript-estree"
        "glob"
    )

    # Symlink each test package if it exists in assessment and not in workspace
    for pkg in "${TEST_PACKAGES[@]}"; do
        # Handle scoped packages (e.g., @vitejs/plugin-react-swc)
        if [[ "$pkg" == @* ]]; then
            scope="${pkg%%/*}"
            package_name="${pkg#*/}"

            # Create scope directory if it doesn't exist
            mkdir -p "/workspace/node_modules/$scope"

            # Symlink if not already present
            if [ ! -e "/workspace/node_modules/$pkg" ] && [ -d "/usr/local/share/assessment/node_modules/$pkg" ]; then
                ln -sf "/usr/local/share/assessment/node_modules/$pkg" "/workspace/node_modules/$pkg"
            fi
        else
            # Non-scoped package
            if [ ! -e "/workspace/node_modules/$pkg" ] && [ -d "/usr/local/share/assessment/node_modules/$pkg" ]; then
                ln -sf "/usr/local/share/assessment/node_modules/$pkg" "/workspace/node_modules/$pkg"
            fi
        fi
    done

    echo "   ✓ Test dependencies linked"
}

start_dev_server() {
    # 8. Auto-start the development server
    echo "🚀 Starting development server via 'npm run dev'..."
    cd /workspace
    # Start npm run dev in the background, redirect output to a log file
    # We use npm run dev to pick up polling settings from package.json
    nohup npm run dev > /workspace/.dev-server.log 2>&1 &
    
    # Warm up server in background to trigger initial compilation
    (
        echo "🔥 Waiting for Next.js to be ready..."
        # Wait for port 3000 to be open and responding (max 60s)
        for i in {1..60}; do
            # Check if port is open AND if curl can get a response
            # We use localhost:3000 but Next.js will see it as a request to the root
            if lsof -i :3000 >/dev/null && curl -s -f http://localhost:3000/ > /dev/null 2>&1; then
                echo "✅ Next.js is ready! Compilation triggered."
                # One more request just to be sure
                curl -s http://localhost:3000/ > /dev/null
                break
            fi
            [ $((i % 5)) -eq 0 ] && echo "⏳ Waiting for server to respond on port 3000... ($i/60)"
            sleep 1
        done
    ) &

    echo "✅ Development server background process started"
    echo "   Logs: tail -f /workspace/.dev-server.log"
}

# ============================================
# BACKGROUND SETUP FUNCTION
# Runs AFTER code-server starts
# ============================================
run_background_setup() {
    echo "⏳ Running background setup..."

    # Fix workspace permissions - simplified
    echo "🔧 Fixing workspace permissions..."
    sudo chown -R coder:coder /workspace/.next /workspace/.env* 2>/dev/null || true &
    
    measure_step "setup_claude_auth" setup_claude_auth
    measure_step "setup_claude_wrapper" setup_claude_wrapper
    measure_step "setup_bash_config" setup_bash_config
    measure_step "setup_git" setup_git
    measure_step "setup_env_local" setup_env_local
    measure_step "setup_test_deps" setup_test_deps
    measure_step "start_dev_server" start_dev_server


    # Final ownership check
    chown -R coder:coder /home/coder/.claude 2>/dev/null || true

    echo "✅ Background setup complete!"
}

# ============================================
# MAIN: Start code-server
# ============================================

# CRITICAL: Ensure settings are valid and owned by coder BEFORE starting
# This prevents code-server from loading default settings (ignoring our config)
check_settings() {
    SETTINGS_PATH="/home/coder/.local/share/code-server/User/settings.json"
    BACKUP_PATH="/home/coder/.local/share/code-server/User/settings.json.bak"
    
    echo "⚙️  Enforcing default settings..."
    # Always overwrite with enforced settings to prevent persistence of theme changes etc.
    if [ -f "$BACKUP_PATH" ]; then
         cp "$BACKUP_PATH" "$SETTINGS_PATH"
         sudo chown coder:coder "$SETTINGS_PATH"
         echo "✅ Settings enforced from backup"
    else
         echo "⚠️  Backup settings missing, skipping enforcement"
    fi

    # Force remove GitHub Copilot extensions directly in the entrypoint
    # This runs synchronously BEFORE code-server starts to prevent them from loading
    echo "🚫 Removing GitHub Copilot extensions..."
    rm -rf /home/coder/.local/share/code-server/extensions/GitHub.copilot* 2>/dev/null || true
    rm -rf /home/coder/.local/share/code-server/extensions/GitHub.copilot-chat* 2>/dev/null || true
}

echo "🛠️  Verifying configuration..."
check_settings

# Fix workspace permissions synchronously for the root folder
# This ensures code-server can actually read the workspace directory on launch
echo "🔧 Fixing workspace permissions..."
