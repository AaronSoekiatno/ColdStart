# ============================================
# PERFORMANCE LOGGING
# ============================================
log_metric() {
    local name="$1"
    local duration="$2"
    local extra="${3:-}"
    echo "METRIC::${name}::${duration}ms ${extra}"
}

measure_step() {
    local step_name="$1"
    shift
    local start_ts=$(date +%s%3N)
    "$@"
    local ret=$?
    local end_ts=$(date +%s%3N)
    local duration=$((end_ts - start_ts))
    log_metric "$step_name" "$duration"
    return $ret
}

