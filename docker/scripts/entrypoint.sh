#!/bin/bash
# ============================================
# Hermes Assessment Environment Entrypoint
# ============================================
# Theia IDE Version - Clean and simple
# ============================================

echo "🚀 Starting Hermes Assessment Environment (Theia IDE)..."
echo "============================================"

# Display build version
VERSION_FILE="${HOME}/.hermes-version.json"
if [ -f "$VERSION_FILE" ]; then
    echo "📦 Container Version:"
    cat "$VERSION_FILE" | node -e 'const fs = require("fs"); const d = JSON.parse(fs.readFileSync(0, "utf-8")); console.log("   Built: " + d.built_at + " | IDE: " + (d.ide || "theia"))'
    echo "============================================"
fi

# Ensure Supabase Service Key is available
export SUPABASE_SERVICE_KEY=${SUPABASE_SERVICE_KEY:-$SUPABASE_SERVICE_ROLE_KEY}
export NEXT_TELEMETRY_DISABLED=1

# ============================================
# PERFORMANCE LOGGING
# ============================================
log_metric() {
    local name="$1"
    local duration="$2"
    local extra="${3:-}"
    echo "METRIC::${name}::${duration}ms ${extra}"
}

measure_step() {
    local step_name="$1"
    shift
    local start_ts=$(date +%s%3N)
    "$@"
    local ret=$?
    local end_ts=$(date +%s%3N)
    local duration=$((end_ts - start_ts))
    log_metric "$step_name" "$duration"
    return $ret
}

# ============================================
# SETUP FUNCTIONS
# ============================================

setup_bash_config() {
    cat >> ${HOME}/.bashrc << 'BASHRC'
export PATH="$HOME/.local/bin:$PATH"
BASHRC
}

setup_git() {
    echo "📝 Configuring Git..."
    git config --global user.name "${GIT_USER_NAME:-Candidate}"
    git config --global user.email "${GIT_USER_EMAIL:-candidate@assessment.local}"
    git config --global init.defaultBranch main

    if [ ! -d "/workspace/.git" ]; then
        echo "📁 Initializing workspace..."
        cd /workspace
        git init
        git config user.email "${GIT_USER_EMAIL:-candidate@hermes.com}"
        git config user.name "${GIT_USER_NAME:-Candidate}"
        git add -A 2>/dev/null || true
        git commit -m "Initial workspace setup" 2>/dev/null || true
    fi
}

setup_env_local() {
    echo "🔑 Provisioning credentials to .env.local..."
    ENV_FILE="/workspace/.env.local"
    echo "# Auto-generated by Hermes Assessment Environment" > "$ENV_FILE"
    KEYS=("CANDIDATE_ID" "SESSION_ID" "NEXT_PUBLIC_SUPABASE_URL" "NEXT_PUBLIC_SUPABASE_ANON_KEY" "GEMINI_BASE_URL" "GOOGLE_BASE_URL" "GOOGLE_API_KEY" "QUARTERMASTER_API_URL")

    for KEY in "${KEYS[@]}"; do
        if [ -n "${!KEY}" ]; then
            echo "$KEY=${!KEY}" >> "$ENV_FILE"
        fi
    done

    echo "HOST=0.0.0.0" >> "$ENV_FILE"
    echo "PORT=3000" >> "$ENV_FILE"
}

start_dev_server() {
    echo "🚀 Starting development server via 'npm run dev'..."
    cd /workspace
    nohup npm run dev > /workspace/.dev-server.log 2>&1 &
    
    # Warm up server in background
    (
        echo "🔥 Waiting for Next.js to be ready..."
        for i in {1..60}; do
            if curl -s -f http://localhost:3000/ > /dev/null 2>&1; then
                echo "✅ Next.js is ready! Compilation triggered."
                curl -s http://localhost:3000/ > /dev/null
                break
            fi
            [ $((i % 5)) -eq 0 ] && echo "⏳ Waiting for server to respond on port 3000... ($i/60)"
            sleep 1
        done
    ) &

    echo "✅ Development server background process started"
    echo "   Logs: tail -f /workspace/.dev-server.log"
}

# ============================================
# BACKGROUND SETUP
# ============================================
run_background_setup() {
    echo "⏳ Running background setup..."

    # Fix workspace permissions
    echo "🔧 Fixing workspace permissions..."
    sudo chown -R theia:theia /workspace/.next /workspace/.env* 2>/dev/null || true &
    
    measure_step "setup_bash_config" setup_bash_config
    measure_step "setup_git" setup_git
    measure_step "setup_env_local" setup_env_local
    measure_step "start_dev_server" start_dev_server

    echo "✅ Background setup complete!"
}

# ============================================
# MAIN: Start Theia IDE
# ============================================

# Fix workspace permissions
echo "🔧 Fixing workspace permissions..."
sudo chown theia:theia /workspace

echo "🖥️  Starting Theia IDE on 0.0.0.0:8080..."
START_TIME=$(date +%s%3N)

# Run setup tasks in background
run_background_setup &

# Log startup performance
END_TIME=$(date +%s%3N)
STARTUP_DURATION=$((END_TIME - START_TIME))
log_metric "theia_startup" "$STARTUP_DURATION"

# Start Theia (this blocks and keeps container running)
# Theia automatically binds to the port and serves the workspace
cd /home/theia

# Check if we're using the official Theia image structure
if [ -f "/home/theia/src-gen/backend/main.js" ]; then
    exec node /home/theia/src-gen/backend/main.js \
        --hostname=0.0.0.0 \
        --port=8080 \
        /workspace
elif [ -f "/home/theia/applications/browser/lib/backend/main.js" ]; then
    exec node /home/theia/applications/browser/lib/backend/main.js \
        --hostname=0.0.0.0 \
        --port=8080 \
        /workspace
else
    # Fallback: try to find main.js
    THEIA_MAIN=$(find /home/theia -name "main.js" -path "*backend*" | head -n 1)
    if [ -n "$THEIA_MAIN" ]; then
        exec node "$THEIA_MAIN" \
            --hostname=0.0.0.0 \
            --port=8080 \
            /workspace
    else
        echo "❌ Could not find Theia main.js!"
        echo "Available files:"
        ls -la /home/theia/
        exit 1
    fi
fi
